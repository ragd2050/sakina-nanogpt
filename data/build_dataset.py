def main():
    with open(ROOT / "existing_labeled_examples.json", encoding="utf-8-sig") as f:
        existing = json.load(f)

    combined = []
    counters = {e: 0 for e in TAGS}

    for row in existing:
        emo = row.get("detected_emotion")
        if emo in DROP_EMOTIONS:
            continue
        emo = RENAME_MAP.get(emo, emo)
        if emo not in TAGS:
            continue

        idx = counters[emo]
        counters[emo] += 1

        verses = EMOTION_VERSES[emo]
        comforts = COMFORT_BANK[emo]

        combined.append({
            "user_input": row["user_input"],
            "detected_emotion": emo,
            "emotion_tag": TAGS[emo],
            "verse_id": verses[idx % len(verses)],
            "comfort_message": comforts[idx % len(comforts)],
            "source": row.get("source", "existing"),
        })

    for emo, texts in NEW_EXAMPLES.items():
        verses = EMOTION_VERSES[emo]
        comforts = COMFORT_BANK[emo]
        for idx, text in enumerate(texts):
            combined.append({
                "user_input": text,
                "detected_emotion": emo,
                "emotion_tag": TAGS[emo],
                "verse_id": verses[idx % len(verses)],
                "comfort_message": comforts[idx % len(comforts)],
                "source": "Sakina_new_v10",
            })

    out_path = ROOT / "emotions_dataset.json"
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(combined, f, ensure_ascii=False, indent=2)

    print(f"Wrote {len(combined)} examples to {out_path}")
    from collections import Counter
    print(Counter(r["detected_emotion"] for r in combined))


if __name__ == "__main__":
    main()
